/* Dimming data arrays */
#define DIMMING_CURVE_SIZE 401U
static uint32_t led_ramp_warm[DIMMING_CURVE_SIZE] = {RESET_VALUE};
static uint32_t led_ramp_cool[DIMMING_CURVE_SIZE] = {RESET_VALUE};

/* Allocate memory for smooth_led_dimming_ctrl block */
static smooth_led_dimming_ctrl_t smooth_led_dimming_ctrl_place_holder[RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG] = {0};
/*
 * Initialize data/controls structure and set number of led bulbs using in a LED bulb dimming system
 * These settings must be set to the following structure before starting using the module
 *
 * */
static led_bulb_dimming_ctrl_instance_t g_bulb_ctrl =
{
    /*
     * The bulb_num parameter specifies the number of LED bulbs managed by a Smooth LED Lighting Control instance.
     * Each LED bulb requires a dedicated PWM timer and PWM outputs to independently control its warm-white and cool-white LED channels.
     * The minimum hardware resources required for a single LED bulb are summarized below.
     * - Fading control/periodic timer: 1
     * - PWM timer: 1.
     * - PWM output: 2
     *
     * Sharing Resources Across Multiple LED Bulbs:
     * - A led_bulb_dimming_ctrl_instance_t can control multiple LED bulbs by sharing a single fading-control timer while using multiple PWM timers.
     * - For example:
     * led_bulb_dimming_ctrl_instance_t
     * │
     * ├── GPT Fading Timer
     * │
     * ├── PWM Timer 0
     * │   │
     * │   ├── GTIOCA → Warm LED Bulb 0
     * │   └── GTIOCB → Cool LED Bulb 0
     * │
     * ├── PWM Timer
     * │   │
     * │   ├── GTIOCA → Warm LED Bulb 1
     * │   └── GTIOCB → Cool LED Bulb 1
     * │
     * └── PWM Timer 2
     *      ├── GTIOCA → Warm LED Bulb 2
     *      └── GTIOCB → Cool LED Bulb 2
     * In this configuration, all bulbs follow the same dimming cadence generated by the shared fading timer.
     *
     * Multiple Dimming Control Instances:
     * - A system may contain multiple led_bulb_dimming_ctrl_instance_t instances.
     * - Each instance can:
     *   + Control a different group of LED bulbs.
     *   + Use a different dimming table to implement different warm/cool LED mixing profiles.
     *   + Use different fade rates or timing parameters.
     *   + Operate independently of other lighting groups.
     * - For example:
     * Instance 0
     * ├── Living Room LEDs
     * ├── Slow Fade Profile
     * └── Warm-to-Cool Mixing
     *
     * Instance 1
     * ├── Kitchen LEDs
     * ├── Fast Fade Profile
     * └── Cool-White Bias
     *
     * Instance 2
     * ├── Accent Lighting
     * ├── Custom Dimming Curve
     * └── Warm-White Output
     *
     * This architecture provides a scalable and flexible framework for controlling multiple LED bulbs
     * and lighting zones while maintaining smooth brightness transitions and minimal CPU utilization
     * through the use of GPT timers, DMAC transfers, and ELC-triggered hardware events.
     *
     * */
    .bulb_num                         = RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG,
    /* The count of generated LED bulb dimming controls, it keeps track the number of dimming blocks until it reach the bulb_num setting */
    .led_dimming_info.bulb_config_cnt = 0,
    /* Set to close state */
    .led_dimming_info.open            = false,
    /* point to smooth_led_dimming_ctrl_place_holder */
    .p_led_dimming_ctrl               = &smooth_led_dimming_ctrl_place_holder[RESET_VALUE],
    /* Pointer to module APIs block */
    .p_led_dimming_function           = &g_dimming_ctrl_on_led_bulb,
};

/*****************************************************************************************************************
 * @brief       Generate Tunable White Perceptual Dimming Curve.
 * @param[in]   Smooth LED Lighting Control instance, LED dimming target.
 * @retval      FSP_SUCCESS  Upon successful generating data.
 * @retval      SP_ERR_INVALID_POINTER, FSP_ERR_INVALID_ARGUMENT errors
 *
 * Generate Tunable White Perceptual Dimming Curve.
 *
 * Brightness:
 *     B(x) = 0.7x² + 0.3x
 * Cool mix:
 *     C(x) = 0                                        , x < 0.30
 *          = ((x - 0.30) / 0.70)^3                    , x >= 0.30
 * Warm mix:
 *     W(x) = 1 - 0.8C(x)
 * PWM outputs:
 *     PWMwarm = Period × B(x) × W(x)
 *     PWMcool = Period × B(x) × C(x)
 *
 **********************************************************************************************************************/
static fsp_err_t smooth_led_lighting_dimming_curve (uint32_t * const p_led_ramp_warm, uint32_t * const p_led_ramp_cool, uint32_t const curve_size, uint32_t const period)
{
    /* Parameter Checks */
    if ((NULL == p_led_ramp_warm) || (NULL == p_led_ramp_cool))
    {
        return FSP_ERR_INVALID_POINTER;
    }

    if ((curve_size < 2U) || (0U == period))
    {
        return FSP_ERR_INVALID_ARGUMENT;
    }

    /* Curve tuning constants */
    const float brightness_quad_weight = 0.7f;
    const float brightness_lin_weight  = 0.3f;
    const float cool_start             = 0.30f;
    const float cool_range             = 1.0f - cool_start;
    const float warm_retention         = 0.8f;
    uint32_t const steps               = curve_size - 1U;

    /* Step 0 = OFF */
    p_led_ramp_warm[0] = 0U;
    p_led_ramp_cool[0] = 0U;

    for (uint32_t i = 1U; i <= steps; i++)
    {
        /* Normalize ramp position */
        float x = (float) i / (float) steps;
        /* Perceptual brightness curve */
        float brightness = (brightness_quad_weight * x * x) + (brightness_lin_weight  * x);

        /* Cool-white mixing */
        float cool_mix = 0.0f;

        if (x >= cool_start)
        {
            float t = (x - cool_start) / cool_range;
            /* Cubic grow-in for cool LED */
            cool_mix = t * t * t;
            if (cool_mix > 1.0f)
            {
                cool_mix = 1.0f;
            }
        }

        /* Warm-white mixing */
        float warm_mix    = 1.0f - (warm_retention * cool_mix);

        /* Generate PWM values */
        float warm_pwm    = ((float) period * brightness * warm_mix);
        float cool_pwm    = ((float) period * brightness * cool_mix);

        /* Add 0.5f for PWM count rounding */
        p_led_ramp_warm[i] = (uint32_t)(warm_pwm + 0.5f);
        p_led_ramp_cool[i] = (uint32_t)(cool_pwm + 0.5f);
    }

    return FSP_SUCCESS;
}

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void smooth_led_lighting_demo(void)
{
    fsp_err_t           err         = FSP_SUCCESS;
    int                 cmd         = RESET_VALUE;
    const char * dimLevel[]         = {"", "Low", "Med", "High", "Full On"};
    uint8_t             currentDim  = Med; //Keep LED current dimming level for ON cmd, set to medium by default
    const uint16_t dimIndex[LED_STAGE_NUM]  = {0, 100, 200, 300, 400};

    /* Copy necessary module configurations into LED lighting configuration in SRAM */
    for(int i = 0; i < (int)g_bulb_ctrl.bulb_num; i++)
    {
        switch (i)
        {
            case LED_BULB_1: //1st LED bulb: Initialize 1 PWM channel/2 PWM outputs, 2 DMAC channels, 1 common fading timer control channel used in a "led_bulb_dimming_ctrl_instance_t"
            {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                err = g_bulb_ctrl.p_led_dimming_function->CommonConfigGen(&g_bulb_ctrl, &gpt_fade_preset, &g_elc_preset, &led_ramp_warm[0], &led_ramp_cool[0]);
#else
                err = g_bulb_ctrl.p_led_dimming_function->CommonConfigGen(&g_bulb_ctrl, &gpt_fade, &g_elc, &led_ramp_warm[0], &led_ramp_cool[0]);
#endif
                if(FSP_SUCCESS != err)
                {
                    /* Return the configuration err */
                    err = FSP_ERR_INVALID_ARGUMENT;
                 }
            }
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                err  = g_bulb_ctrl.p_led_dimming_function->ControlConfigGen(&g_bulb_ctrl, &gpt_led_preset, &tx_warm_color_preset, &tx_cool_color_preset);
#else
                err  = g_bulb_ctrl.p_led_dimming_function->ControlConfigGen(&g_bulb_ctrl, &gpt_led, &tx_warm_color, &tx_cool_color);
#endif
                if(err != FSP_SUCCESS)
                {
                   // Trap here as error
                   __BKPT(1);
                 }
            break;
#if (RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG >1)
            case LED_BULB_2: //2nd LED bulb: Initialize 1 PWM channel/2 outputs, 2 DMAC channels
            {
                err  = g_bulb_ctrl.p_led_dimming_function->ControlConfigGen(&g_bulb_ctrl, &gpt_led1,&tx_warm_color1, &tx_cool_color1);
                if(err != FSP_SUCCESS)
                {
                   // Trap here as error
                   __BKPT(1);
                 }
            }
            break;
#if (RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG > 2)
            case LED_BULB_3: //3rd LED bulb: Initialize 1 PWM channel/2 outputs, 2 DMAC channels
            {
                err  = g_bulb_ctrl.p_led_dimming_function->ControlConfigGen(&g_bulb_ctrl, &gpt_led2, &tx_warm_color2, &tx_cool_color2);
                if(err != FSP_SUCCESS)
                {
                   // Trap here as error
                   __BKPT(1);
                 }
            }
            break;
#endif //RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG >2
#endif //RS_SMOOTH_LED_LIGHTING_BULB_NUM_CFG >1
            default:
            break;
        }
    }

    /*
     * Start checking module configurations
     *  */
    {
         /* Check pointers to FSP APIs: ELC, GPT timer, DMAC */
         err = g_bulb_ctrl.p_led_dimming_function->GenericPointerCheck((elc_api_t *)g_bulb_ctrl.p_elc_api,(elc_api_t *) &g_elc_on_elc);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }
         err = g_bulb_ctrl.p_led_dimming_function->GenericPointerCheck((timer_api_t *)g_bulb_ctrl.p_timer_api, (timer_api_t *)&g_timer_on_gpt);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }
         err = g_bulb_ctrl.p_led_dimming_function->GenericPointerCheck((transfer_api_t *)g_bulb_ctrl.p_transfer_api, (transfer_api_t *)&g_transfer_on_dmac);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }

         /* Verify GPT configurations */
         err = g_bulb_ctrl.p_led_dimming_function->GPTLEDConfigCheck(&g_bulb_ctrl, (timer_cfg_t *)&gpt_led_cfg_std, (gpt_extended_cfg_t *)&gpt_led_ext_cfg_std);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }

         err = g_bulb_ctrl.p_led_dimming_function->GPTFadingConfigCheck(&g_bulb_ctrl, &gpt_fade_cfg_std);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }

        /* Check DMAC Info extended configurations vs the standard settings */
        err = g_bulb_ctrl.p_led_dimming_function->TXInfoExtConfigCheck(&g_bulb_ctrl, &tx_info_std, &tx_ext_cfg_std);
        if(err != FSP_SUCCESS)
        {
            // Trap here as error
            __BKPT(1);
        }
    }
    /*
     * End checking module configurations
     * */


#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
    /* Turn off the LEDs */
     err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Off]);
#else
     /* Turn off the LEDs */
     err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Off]);
#endif
     if(err != FSP_SUCCESS)
     {
         // Trap here as error
         __BKPT(1);
     }

     /*
      * Generate Tunable White Perceptual Dimming Curve (0% duty == LED OFF)
      * This would normally be a constant table in flash once the curve is determined
     */
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
     uint32_t period = gpt_led_cfg_preset.period_counts;
#else
     uint32_t period = gpt_led_cfg.period_counts;
#endif
     err = smooth_led_lighting_dimming_curve(&led_ramp_warm[0], &led_ramp_cool[0], DIMMING_CURVE_SIZE, period);
     if(err != FSP_SUCCESS)
     {
         // Trap here as error
         __BKPT(1);
     }
     /* Print module info */
     printf(BANNER);
     printf("\r\nNumber of LED Bulb : %d\r\n", g_bulb_ctrl.bulb_num);
     printf("\r\nFading control timer : GPT CH%d\r\n", g_bulb_ctrl.fade_timer_led_ctrl.gpt_dimming_fade_cfg.channel);
     for(int i = 0; i < (int)g_bulb_ctrl.bulb_num; i++)
     {
         printf("\r\nPWM%d : GPT CH%d\r\n", (i+1), g_bulb_ctrl.p_led_dimming_ctrl[i].gpt_dimming_led_cfg.channel);
     }

     /* Print option menu*/
     printf(OPTION_MENU);
     while (true)
     {
         cmd = getchar();
         switch(cmd)
         {
             case DIMMING_LEVEL_OFF_CHAR:
             {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
               err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Off]);
#else
               err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Off]);
#endif
               printf("\r\nCMD : %c - OFF\r\n", cmd);
             }
             break;
             case DIMMING_LEVEL_LOW_CHAR:
             {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                  err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Low]);
#else
                  err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Low]);
#endif
                  currentDim = (uint8_t)Low;
                  printf("\r\nCMD : %c - LOW\r\n", cmd);
             }
             break;
             case DIMMING_LEVEL_MED_CHAR:
             {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Med]);
#else
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Med]);
#endif
                   currentDim = (uint8_t)Med;
                   printf("\r\nCMD : %c - MED\r\n", cmd);
             }
             break;
             case DIMMING_LEVEL_HIGH_CHAR:
             {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[High]);
#else
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[High]);
#endif
                   currentDim = (uint8_t)High;
                   printf("\r\nCMD : %c - HIGH\r\n", cmd);
             }
             break;
             case DIMMING_LEVEL_FULL_ON_CHAR:
             {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Full_on]);
#else
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[Full_on]);
#endif
                   currentDim = (uint8_t)Full_on;
                   printf("\r\nCMD : %c - FULL_ON\r\n", cmd);
             }
             break;
             case DIMMING_LEVEL_ON_CHAR:
             {
                 /* Note: LED needs to be in Off state before turning on*/
                 if(dimIndex[Off] == g_bulb_ctrl.led_dimming_info.led_dimming_stage.led_stage)
                 {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[currentDim]);
#else
                   err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[currentDim]);
#endif
                   printf("\r\nCMD : %c - ON : %s\r\n", cmd, dimLevel[currentDim]);
                 }
                 else
                 {
                   printf("\r\nCMD : %c - ON : LED is already ON. Skip the CMD\r\n", cmd);
                 }
             }
             break;
             case DIMMING_LEVEL_DIMMER_CHAR:
             {
               if(dimIndex[Off] != g_bulb_ctrl.led_dimming_info.led_dimming_stage.led_stage)
               {
                   if(currentDim > (uint8_t)Low)
                   {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                       err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[--currentDim]);
#else
                       err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[--currentDim]);
#endif
                       printf("\r\nCMD : %c - Dimmer : %s\r\n", cmd, dimLevel[currentDim]);
                   }
                   else if(currentDim == Low) // Dimming Level Off
                   {
                       printf("\r\nCMD : %c - Dimmer : LED Dimming is at Low Level, Skip the CMD\r\n", cmd);
                   }
               }
               else
               {
                   printf("\r\nCMD : %c - Dimmer : LED is not turned on. Use [1]/[2]/[3]/[4]/[5] CMD to set dimming level\r\n", cmd);
               }
             }
             break;
             case DIMMING_LEVEL_BRIGHTER_CHAR:
             {
                 if(dimIndex[Off] != g_bulb_ctrl.led_dimming_info.led_dimming_stage.led_stage)
                 {
                   if(currentDim < (uint8_t)Full_on)
                   {
#if RS_SMOOTH_LED_LIGHTING_PRESET_CFG_USE // Use pre-set configuration for Smooth Lighting LED
                       err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[++currentDim]);
#else
                       err = g_bulb_ctrl.p_led_dimming_function->IntensitySet(&g_bulb_ctrl, &dimIndex[++currentDim]);
#endif
                       printf("\r\nCMD : %c - Brighter : %s\r\n", cmd, dimLevel[currentDim]);
                   }
                   else if(currentDim == (uint8_t)Full_on) // Dimming Level Full-on
                   {
                       printf("\r\nCMD : %c - Brighter : LED is FULL-ON, Skip the CMD \r\n", cmd);
                   }
                 }
                 else
                 {
                     printf("\r\nCMD : %c - Brighter : LED is not turned on. Use [1]/[2]/[3]/[4]/[5] CMD to set dimming level\r\n", cmd);
                 }
             }
             break;

             default:
                 printf("\r\nInvalid Input\r\n");
         }
         fflush(stdout);
         if(err != FSP_SUCCESS)
         {
             // Trap here as error
             __BKPT(1);
         }
         printf(OPTION_MENU);
     }
}

/*******************************************************************************************************************//**
 *  @brief      DMAC call back function
 *  @param[in]  callback arguments
 **********************************************************************************************************************/
void tx_callback(dmac_callback_args_t * p_args)
{
    FSP_PARAMETER_NOT_USED(p_args);

    /* Update dimming/LED stage */
    g_bulb_ctrl.led_dimming_info.led_dimming_stage.led_stage = g_bulb_ctrl.led_dimming_info.led_dimming_stage.led_target;
}

